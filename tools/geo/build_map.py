# Colombia map for the zone selector (v3.60): departments (DANE MGN 2018, pre-simplified),
# each mapped to its game region, projected onto a flat plane (x: longitude, y: latitude, in
# units of 1/40 degree) and written to src/data/colombiaMap.js.
# Usage: python3 tools/geo/build_map.py [path to geojson]; without path, downloads from SOURCE.
import json, os, sys, urllib.request

SOURCE = 'https://raw.githubusercontent.com/caticoa3/colombia_mapa/master/co_2018_MGN_DPTO_POLITICO.geojson'
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'data', 'colombiaMap.js')
K = 40  # units per degree
LON0, LAT0 = -79.1, 12.6  # top-left corner (San Andrés is excluded)

# DANE department code → game region (unlisted ones render in gray).
REGION = {
    '17': 'cafetero', '63': 'cafetero', '66': 'cafetero', '05': 'cafetero',
    '68': 'santander', '54': 'santander',
    '08': 'costa', '13': 'costa', '20': 'costa', '23': 'costa', '44': 'costa', '47': 'costa', '70': 'costa',
    '15': 'boyaca',
    '50': 'llanos', '81': 'llanos', '85': 'llanos', '99': 'llanos',
    '27': 'pacifico', '76': 'pacifico', '19': 'pacifico', '52': 'pacifico',
    '91': 'amazonas', '18': 'amazonas', '86': 'amazonas', '95': 'amazonas', '94': 'amazonas', '97': 'amazonas',
}
SKIP = {'88'}  # San Andrés: too far off the coast for this map


def proj(lon, lat):
    return round((lon - LON0) * K, 1), round((LAT0 - lat) * K, 1)


def ring_path(ring):
    pts = [proj(*p[:2]) for p in ring]
    return 'M' + 'L'.join(f'{x:g},{y:g}' for x, y in pts) + 'Z'


def main():
    if len(sys.argv) > 1:
        data = json.load(open(sys.argv[1], encoding='utf-8'))
    else:
        with urllib.request.urlopen(SOURCE) as r:
            data = json.load(r)
    depts = []
    for f in data['features']:
        code = f['properties']['DPTO_CCDGO']
        if code in SKIP:
            continue
        g = f['geometry']
        polys = [g['coordinates']] if g['type'] == 'Polygon' else g['coordinates']
        d = ''.join(ring_path(ring) for poly in polys for ring in poly)
        name = f['properties']['DPTO_CNMBR'].title().replace(' De ', ' de ').replace(' Del ', ' del ').replace(', D.C.', '')
        depts.append({'id': code, 'name': name, 'region': REGION.get(code), 'd': d})
    depts.sort(key=lambda x: x['id'])
    lines = [
        '// Colombia map (v3.60): departments with their game region (null: none), in units of',
        '// 1/40 degree (x increases east, y increases south). Generated by tools/geo/build_map.py',
        '// from DANE Marco Geoestadístico Nacional 2018; do not edit by hand.',
        f'export const MAP_SCALE = {K};',
        f'export const MAP_ORIGIN = [{LON0}, {LAT0}]; // [longitude, latitude] of the top-left corner',
        'export const DEPARTMENTS = [',
    ]
    for d in depts:
        region = f"'{d['region']}'" if d['region'] else 'null'
        lines.append(f"  {{ id: '{d['id']}', name: '{d['name']}', region: {region}, d: '{d['d']}' }},")
    lines.append('];')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(OUT, len(depts), 'departamentos', os.path.getsize(OUT), 'bytes')


main()
